# ## 12. Memory Allocation
#
# Memory allocation means providing space in computer memory to store variables, functions, objects and other data while a program is running.
#
# ### Example:
#
# ```python
# x = 10
# ```
#
# Here, memory is allocated to store the value `10`, and `x` refers to that value.
#
# ---
#
# ## 13. Memory in Procedural Programming
#
# Procedural programs mainly work with variables and function calls.
#
# Simple procedural programs may require less memory compared with equivalent object-oriented programs because they do not need to create objects for every operation.
#
# ### Example:
#
# ```python
# x = 10
# calculate()
# ```
#
# Here, the program uses a variable and a function call.
#
# ---
#
# ## 14. Memory in OOP
#
# In OOP, objects store their own data or attributes.
#
# Creating objects requires memory to store their data.
#
# ### Example:
#
# ```text
# Car Object
#
# color = "Red"
# model = "BMW"
# ```
#
# Here, the Car object stores information such as color and model.
#
# ---
#
# ## 15. Procedural vs OOP Memory
#
# ### Procedural Programming:
#
# * Mainly uses variables and functions.
# * Generally has less object-related memory overhead.
#
# ### OOP:
#
# * Uses objects, attributes and methods.
# * Objects require memory to store their data.
# * May use more memory because of object creation.
#
# ### Easy to Remember:
#
# **Procedural → Variables + Functions**
#
# **OOP → Objects + Attributes + Methods**
