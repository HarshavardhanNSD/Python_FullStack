# # INTRODUCTION TO PROGRAMMING & PYTHON
#
# ## 1. What is Programming?
#
# #Programming means giving instructions to a computer to perform a specific task.
#
# ### Example:
#
# ```python
# print("Hello")
# ```
#
# ---
#
# ## 2. What is a Programming Language?
#
# A programming language is used to communicate with a computer and create applications or software.
#
# ### Examples:
#
# * Python
# * Java
# * C
# * C++
#
# ---
#
# ## 3. Programming Paradigms
#
# A programming paradigm is a way or style of writing programs.
#
# ### Types:
#
# 1. Procedural Programming
# 2. Object-Oriented Programming (OOP)
#
# ---
#
# ## 4. Procedural Programming
#
# Procedural programming solves a problem step by step using functions or procedures.
#
# ### Example:
#
# ```python
# login()
# payment()
# confirm_order()
# ```
#
# ### Key Points:
#
# * Focuses on functions.
# * Follows a step-by-step approach.
# * Suitable for simple and smaller programs.
#
# ---
#
# ## 5. Object-Oriented Programming (OOP)
#
# Object-Oriented Programming organizes programs using classes and objects.
#
# It is useful for developing large and complex applications.
#
# ### Example:
#
# A Car can have:
#
# **Attributes:**
#
# * Color
# * Model
#
# **Methods:**
#
# * start()
# * stop()
#
# ### Example:
#
# ```text
# Car
#   color
#  model
#   start()
#   stop()
# ```
#
# ### Key Points:
#
# * Focuses on objects.
# * Uses classes and objects.
# * Helps in code reusability.
# * Useful for large applications.
#
# ---
#
# ## 6. Procedural Programming vs OOP
#
# | Procedural Programming        | Object-Oriented Programming          |
# | ----------------------------- | ------------------------------------ |
# | Focuses on functions          | Focuses on objects                   |
# | Uses a step-by-step approach  | Uses classes and objects             |
# | Uses variables and functions  | Uses objects, attributes and methods |
# | Suitable for smaller programs | Suitable for large applications      |
# | Example: calculate_bill()     | Example: Customer, Product           |
#
# ### Example:
#
# **Procedural:**
#
# ```python
# calculate_bill()
# ```
#
# **OOP:**
#
# ```text
# Customer
# Product
# Order
# ```
#
# ---
#
